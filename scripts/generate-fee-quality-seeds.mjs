#!/usr/bin/env node
/**
 * Generates seed SQL for fee_taxonomy, fee_key_aliases, and fee_category_bands
 * from the TypeScript sources of truth (src/lib/fee-taxonomy.ts and
 * src/lib/fee-plausibility.ts). Regenerate whenever those files change:
 *
 *   node scripts/generate-fee-quality-seeds.mjs > /tmp/fee-quality-seeds.sql
 *
 * The output is idempotent (ON CONFLICT upserts) and is embedded in the
 * 20270101070000_published_fee_quality_gate migration.
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const taxonomySrc = readFileSync(join(root, "src/lib/fee-taxonomy.ts"), "utf8");
const plausSrc = readFileSync(join(root, "src/lib/fee-plausibility.ts"), "utf8");

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

function extractBlock(src, marker) {
  const start = src.indexOf(marker);
  if (start < 0) throw new Error(`marker not found: ${marker}`);
  const end = src.indexOf("\n};", start);
  return src.slice(start, end);
}

// FEE_FAMILIES: { "Family": ["key", ...] }
const famBlock = extractBlock(taxonomySrc, "export const FEE_FAMILIES");
const families = [];
let current = null;
for (const line of famBlock.split("\n")) {
  const fam = line.match(/^\s{2}"([^"]+)": \[/);
  if (fam) { current = fam[1]; continue; }
  const key = line.match(/^\s{4}"([a-z0-9_]+)",?\s*$/);
  if (key && current) families.push([key[1], current]);
}
if (families.length < 40) throw new Error(`FEE_FAMILIES parse too small: ${families.length}`);

// CANONICAL_KEY_MAP: alias: "canonical"
const mapBlock = extractBlock(taxonomySrc, "export const CANONICAL_KEY_MAP");
const aliases = [...mapBlock.matchAll(/^\s*"?([a-z0-9_]+)"?:\s*"([a-z0-9_]+)",?\s*$/gm)].map(
  (m) => [m[1], m[2]],
);
if (aliases.length < 100) throw new Error(`CANONICAL_KEY_MAP parse too small: ${aliases.length}`);
const canonical = new Set(aliases.map(([, v]) => v));
for (const [k] of families) {
  if (!canonical.has(k)) canonical.add(k);
}

// FEE_ENVELOPES: key: { min: n, max: n, frequencies: [...], note: "..." }
const envBlock = extractBlock(plausSrc, "export const FEE_ENVELOPES");
const envelopes = [...envBlock.matchAll(
  /^\s{2}([a-z0-9_]+):\s*\{\s*min:\s*([\d_.]+),\s*max:\s*([\d_.]+)(?:,\s*frequencies:\s*([A-Z_]+|\[[^\]]*\]))?(?:,\s*note:\s*"([^"]*)")?/gm,
)].map((m) => ({
  key: m[1],
  min: Number(m[2].replaceAll("_", "")),
  max: Number(m[3].replaceAll("_", "")),
  frequencies: m[4] ?? null,
  note: m[5] ?? null,
}));
if (envelopes.length < 30) throw new Error(`FEE_ENVELOPES parse too small: ${envelopes.length}`);
const PER_OCCURRENCE = ["per_item", "per_transaction", "one_time"];
const freqList = (f) => {
  if (!f) return null;
  if (f === "PER_OCCURRENCE") return PER_OCCURRENCE;
  return [...f.matchAll(/"([a-z_]+)"/g)].map((m) => m[1]);
};

const out = [];
out.push("-- Generated by scripts/generate-fee-quality-seeds.mjs; do not hand-edit.");
out.push(`-- Sources: fee-taxonomy.ts (${canonical.size} canonical keys, ${aliases.length} aliases), fee-plausibility.ts (${envelopes.length} envelopes).`);
const famMap = new Map(families);
out.push("INSERT INTO fee_taxonomy (canonical_key, fee_family) VALUES");
out.push(
  [...canonical].sort().map((k) => `  (${lit(k)}, ${famMap.has(k) ? lit(famMap.get(k)) : "NULL"})`).join(",\n") +
  "\nON CONFLICT (canonical_key) DO UPDATE SET fee_family = EXCLUDED.fee_family;",
);
out.push("INSERT INTO fee_key_aliases (alias, canonical_key) VALUES");
out.push(
  aliases.sort().map(([a, c]) => `  (${lit(a)}, ${lit(c)})`).join(",\n") +
  "\nON CONFLICT (alias) DO UPDATE SET canonical_key = EXCLUDED.canonical_key;",
);
out.push("INSERT INTO fee_category_bands (canonical_key, min_amount, max_amount, frequencies, note, source) VALUES");
out.push(
  envelopes.map((e) => {
    const f = freqList(e.frequencies);
    return `  (${lit(e.key)}, ${e.min}, ${e.max}, ${f ? `ARRAY[${f.map(lit).join(", ")}]` : "NULL"}, ${e.note ? lit(e.note) : "NULL"}, 'fee-plausibility v1')`;
  }).join(",\n") +
  "\nON CONFLICT (canonical_key) DO UPDATE SET min_amount = EXCLUDED.min_amount, max_amount = EXCLUDED.max_amount, frequencies = EXCLUDED.frequencies, note = EXCLUDED.note, source = EXCLUDED.source;",
);
process.stdout.write(out.join("\n") + "\n");

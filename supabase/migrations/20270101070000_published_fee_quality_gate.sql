-- Published fee quality gate (Phase 1 of the sellable-intelligence plan, 2026-08-23).
--
-- Adds a quarantine flag to published_fee_records, canonical taxonomy + alias +
-- plausibility-band reference tables (seeded from the TypeScript sources of
-- truth via scripts/generate-fee-quality-seeds.mjs), remaps off-taxonomy keys,
-- retro-flags implausible/zero/duplicate rows, demotes duplicate verified
-- children, and gates the published_fee_catalog view on quality_flag = 'clean'.
--
-- Quarantine only: no row is deleted; every key remap is logged in
-- fee_key_remaps; flags are reversible by UPDATE.
--
-- Apply with psql against DATABASE_URL in a single transaction (see
-- docs/plans/production-migration-history-runbook-2026-08-15.md; db push
-- remains blocked by historical drift).

-- 1. Columns ----------------------------------------------------------------
ALTER TABLE published_fee_records
  ADD COLUMN IF NOT EXISTS quality_flag text NOT NULL DEFAULT 'clean',
  ADD COLUMN IF NOT EXISTS quality_reason text,
  ADD COLUMN IF NOT EXISTS observed_at timestamptz;

ALTER TABLE published_fee_records
  DROP CONSTRAINT IF EXISTS published_fee_records_quality_flag_check;
ALTER TABLE published_fee_records
  ADD CONSTRAINT published_fee_records_quality_flag_check
  CHECK (quality_flag IN ('clean', 'off_taxonomy', 'implausible', 'zero_amount', 'duplicate'));

CREATE INDEX IF NOT EXISTS published_fee_records_quality_idx
  ON published_fee_records (quality_flag)
  WHERE quality_flag <> 'clean';

-- Best available observation date for existing rows; the legacy-promotion
-- phase carries true archive observation dates.
UPDATE published_fee_records SET observed_at = published_at WHERE observed_at IS NULL;

-- 2. Reference tables -------------------------------------------------------
CREATE TABLE IF NOT EXISTS fee_taxonomy (
  canonical_key text PRIMARY KEY,
  fee_family text
);

CREATE TABLE IF NOT EXISTS fee_key_aliases (
  alias text PRIMARY KEY,
  canonical_key text NOT NULL REFERENCES fee_taxonomy (canonical_key)
);

CREATE TABLE IF NOT EXISTS fee_category_bands (
  canonical_key text PRIMARY KEY REFERENCES fee_taxonomy (canonical_key),
  min_amount numeric NOT NULL,
  max_amount numeric NOT NULL,
  frequencies text[],
  note text,
  source text NOT NULL
);

CREATE TABLE IF NOT EXISTS fee_key_remaps (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  entity text NOT NULL,          -- 'published' | 'verified'
  entity_id bigint NOT NULL,
  old_key text NOT NULL,
  new_key text NOT NULL,
  remapped_at timestamptz NOT NULL DEFAULT now()
);


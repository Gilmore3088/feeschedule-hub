-- 3. Remap off-taxonomy canonical keys (logged) -----------------------------
WITH remapped AS (
  UPDATE published_fee_records p
     SET canonical_fee_key = a.canonical_key
    FROM fee_key_aliases a
   WHERE a.alias = p.canonical_fee_key
     AND a.canonical_key <> p.canonical_fee_key
  RETURNING p.fee_published_id, a.alias AS old_key, a.canonical_key AS new_key
)
INSERT INTO fee_key_remaps (entity, entity_id, old_key, new_key)
SELECT 'published', fee_published_id, old_key, new_key FROM remapped;

WITH remapped AS (
  UPDATE verified_fee_observations v
     SET canonical_fee_key = a.canonical_key
    FROM fee_key_aliases a
   WHERE a.alias = v.canonical_fee_key
     AND a.canonical_key <> v.canonical_fee_key
  RETURNING v.fee_verified_id, a.alias AS old_key, a.canonical_key AS new_key
)
INSERT INTO fee_key_remaps (entity, entity_id, old_key, new_key)
SELECT 'verified', fee_verified_id, old_key, new_key FROM remapped;

-- Anything still off-taxonomy (unmappable) is quarantined, not deleted.
UPDATE published_fee_records p
   SET quality_flag = 'off_taxonomy',
       quality_reason = 'canonical_fee_key not in fee_taxonomy and no alias maps it'
 WHERE quality_flag = 'clean'
   AND NOT EXISTS (SELECT 1 FROM fee_taxonomy t WHERE t.canonical_key = p.canonical_fee_key);

-- 4. Hygiene ----------------------------------------------------------------
UPDATE published_fee_records p
   SET source_url = s.fee_schedule_url
  FROM institution_sources s
 WHERE s.id = p.institution_id
   AND p.source_url IS NULL
   AND s.fee_schedule_url IS NOT NULL;

UPDATE fee_change_records SET change_type = 'increased' WHERE change_type = 'increase';

-- 5. Retro-flag amounts -----------------------------------------------------
UPDATE published_fee_records
   SET quality_flag = 'implausible', quality_reason = 'amount is NULL'
 WHERE quality_flag = 'clean' AND amount IS NULL;

UPDATE published_fee_records
   SET quality_flag = 'zero_amount', quality_reason = 'amount is $0 (no-charge line)'
 WHERE quality_flag = 'clean' AND amount = 0;

UPDATE published_fee_records p
   SET quality_flag = 'implausible',
       quality_reason = format('amount %s outside band [%s, %s] (%s)',
                               p.amount, b.min_amount, b.max_amount, b.source)
  FROM fee_category_bands b
 WHERE b.canonical_key = p.canonical_fee_key
   AND p.quality_flag = 'clean'
   AND (p.amount < b.min_amount OR p.amount > b.max_amount);

-- Default ceiling for keys without a band (mirrors DEFAULT_MAX_AMOUNT).
UPDATE published_fee_records p
   SET quality_flag = 'implausible',
       quality_reason = format('amount %s above default ceiling 2500 (no band for %s)',
                               p.amount, p.canonical_fee_key)
 WHERE p.quality_flag = 'clean'
   AND p.amount > 2500
   AND NOT EXISTS (SELECT 1 FROM fee_category_bands b WHERE b.canonical_key = p.canonical_fee_key);

-- 6. Duplicate flagging (keep the lowest id per identical clean line) -------
WITH ranked AS (
  SELECT fee_published_id,
         row_number() OVER (
           PARTITION BY institution_id, canonical_fee_key, COALESCE(variant_type, ''), amount
           ORDER BY fee_published_id
         ) AS rn
    FROM published_fee_records
   WHERE quality_flag = 'clean' AND rolled_back_at IS NULL
)
UPDATE published_fee_records p
   SET quality_flag = 'duplicate',
       quality_reason = 'identical (institution, key, variant, amount) line kept under a lower id'
  FROM ranked r
 WHERE r.fee_published_id = p.fee_published_id AND r.rn > 1;

-- 7. Demote duplicate verified children -------------------------------------
-- The review_status check predates the quarantine flow; extend it first.
ALTER TABLE verified_fee_observations
  DROP CONSTRAINT verified_fee_observations_review_status_check;
ALTER TABLE verified_fee_observations
  ADD CONSTRAINT verified_fee_observations_review_status_check
  CHECK ((review_status = ANY (ARRAY['superseded_duplicate'::text, 'verified'::text, 'challenged'::text, 'rejected'::text, 'approved'::text])));

-- A raw observation is one fee line; keep one verified child per raw
-- (preferring the one a clean published row points at), demote the rest so
-- the publish path stops seeing them. Demotion is reversible.
WITH dup_raws AS (
  SELECT fee_raw_id FROM verified_fee_observations GROUP BY 1 HAVING count(*) > 1
), ranked AS (
  SELECT v.fee_verified_id,
         row_number() OVER (
           PARTITION BY v.fee_raw_id
           ORDER BY (EXISTS (
                      SELECT 1 FROM published_fee_records p
                       WHERE p.lineage_ref = v.fee_verified_id
                         AND p.rolled_back_at IS NULL
                         AND p.quality_flag = 'clean')) DESC,
                    v.fee_verified_id
         ) AS rn
    FROM verified_fee_observations v
    JOIN dup_raws d ON d.fee_raw_id = v.fee_raw_id
)
UPDATE verified_fee_observations v
   SET review_status = 'superseded_duplicate'
  FROM ranked r
 WHERE r.fee_verified_id = v.fee_verified_id AND r.rn > 1
   AND v.review_status IN ('verified', 'approved');

CREATE UNIQUE INDEX IF NOT EXISTS verified_fee_observations_one_live_per_raw
  ON verified_fee_observations (fee_raw_id)
  WHERE review_status IN ('verified', 'approved');

-- 8. Gate the catalog view --------------------------------------------------
CREATE OR REPLACE VIEW published_fee_catalog AS
 SELECT fp.fee_published_id AS id,
    fp.fee_published_id,
    fp.lineage_ref AS fee_verified_id,
    fv.fee_raw_id,
    fp.institution_id,
    fp.fee_name,
    fp.amount,
    fp.frequency,
    fr.conditions,
    COALESCE(fp.extraction_confidence, fv.extraction_confidence, fr.extraction_confidence) AS extraction_confidence,
    'approved'::text AS review_status,
    COALESCE(fv.outlier_flags, '[]'::jsonb) AS validation_flags,
    fp.canonical_fee_key AS fee_category,
    fp.canonical_fee_key,
    NULL::text AS fee_family,
    NULL::text AS account_product_type,
    false AS is_fee_cap,
    fp.variant_type,
    fp.coverage_tier,
    COALESCE(fp.source_url, fv.source_url, fr.source_url) AS source_url,
    fr.source,
    COALESCE(fp.source_url, fv.source_url, fr.source_url) AS document_url,
    COALESCE(fp.document_r2_key, fv.document_r2_key, fr.document_r2_key) AS document_r2_key,
    fr.source_document_id,
    COALESCE(fp.agent_event_id, fr.agent_event_id) AS agent_event_id,
    COALESCE(fp.verified_by_agent_event_id, fv.verified_by_agent_event_id) AS verified_by_agent_event_id,
    fp.published_by_adversarial_event_id,
    fp.batch_id,
    fp.published_at AS created_at,
    fp.published_at AS updated_at,
    fp.quality_flag,
    fp.observed_at
   FROM published_fee_records fp
     LEFT JOIN verified_fee_observations fv ON fv.fee_verified_id = fp.lineage_ref
     LEFT JOIN raw_fee_observations fr ON fr.fee_raw_id = fv.fee_raw_id
  WHERE fp.rolled_back_at IS NULL
    AND fp.quality_flag = 'clean';

-- 9. Invariants (abort the transaction if the gate failed) ------------------
DO $$
DECLARE n bigint;
BEGIN
  SELECT count(*) INTO n FROM published_fee_records p
   WHERE p.quality_flag = 'clean'
     AND NOT EXISTS (SELECT 1 FROM fee_taxonomy t WHERE t.canonical_key = p.canonical_fee_key);
  IF n > 0 THEN RAISE EXCEPTION 'quality gate: % clean rows off-taxonomy', n; END IF;

  SELECT count(*) INTO n FROM (
    SELECT 1 FROM published_fee_records
     WHERE quality_flag = 'clean' AND rolled_back_at IS NULL
     GROUP BY institution_id, canonical_fee_key, COALESCE(variant_type, ''), amount
    HAVING count(*) > 1) d;
  IF n > 0 THEN RAISE EXCEPTION 'quality gate: % duplicate clean groups remain', n; END IF;

  SELECT count(*) INTO n FROM published_fee_records
   WHERE quality_flag = 'clean' AND (amount IS NULL OR amount = 0);
  IF n > 0 THEN RAISE EXCEPTION 'quality gate: % clean rows with NULL/zero amount', n; END IF;
END $$;

